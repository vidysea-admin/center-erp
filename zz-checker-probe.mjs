import { MongoClient, ObjectId } from "mongodb";
const c = new MongoClient(process.env.MONGODB_URL || "mongodb://127.0.0.1:27017");
await c.connect();
const db = c.db(process.env.MONGODB_DB || "center_erp_ci");
const users = await db.collection("users").find({}, { projection: { email:1, role:1, location_scope:1 } }).toArray();
console.log("USERS:");
for (const u of users) console.log("  ", u.email, "|", u.role, "| scope:", (u.location_scope||[]).map(String).join(","));
const locs = await db.collection("locations").find({}, { projection: { name:1, code:1 } }).toArray();
console.log("LOCATIONS:"); for (const l of locs) console.log("  ", String(l._id), l.code, l.name);
const batches = await db.collection("batches").find({}, { projection: { code:1, location:1, status:1 } }).toArray();
console.log("BATCHES:"); for (const b of batches) console.log("  ", String(b._id), b.code, "loc="+String(b.location), b.status);
const logs = await db.collection("dailylogs").aggregate([{ $group: { _id: "$batch", n: {$sum:1}, present: {$sum:"$internal_present"}, roster: {$sum:"$roster_count"} } }]).toArray();
console.log("DAILYLOGS by batch:"); for (const l of logs) console.log("  ", String(l._id), "n="+l.n, "present="+l.present, "roster="+l.roster);
const gar = await db.collection("govtattendancerows").aggregate([{ $group: { _id: { b:"$batch", s:"$match_status" }, n:{$sum:1} } }]).toArray();
console.log("GOVTATTENDANCEROWS by batch/status:", gar.length ? "" : "(NONE)");
for (const g of gar) console.log("  ", String(g._id.b), g._id.s, g.n);
await c.close();
